import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { campusClock } from '@classflow/shared';

test('手册：登记与编辑、搜索、图片、刷新、备份恢复、桌面和手机布局', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto('/');
  await expect(page).toHaveTitle('ClassFlow 班务流');
  await page.getByLabel('管理员账号').fill('tester');
  await page.getByLabel('密码', { exact: true }).fill(process.env.CLASSFLOW_QA_PASSWORD!);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.locator('nav a[href="#handbook"]').click();
  await expect(page.getByRole('heading', { name: '团支部手册', exact: true })).toBeVisible();
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
  const directory = page.getByRole('region', { name: '手册目录' });
  const button = (name: string) => page.getByRole('button', { name, exact: true });
  await directory.getByRole('button', { name: /团员名册/ }).click();
  await button('新增记录').click();
  await page.getByLabel('姓名', { exact: true }).fill('验收同学');
  await page.getByLabel('学号', { exact: true }).fill('QA-2026');
  await page.getByLabel('联系电话', { exact: true }).fill('测试记录');
  await button('保存记录').click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('搜索当前台账').fill('不存在');
  await expect(page.getByText('没有匹配记录')).toBeVisible();
  await page.getByLabel('搜索当前台账').fill('QA-2026');
  await page.locator('.handbook-record').click();
  await page.getByLabel('变动', { exact: true }).fill('验收编辑后保存');
  await button('保存记录').click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.reload();
  await directory.getByRole('button', { name: /团员名册/ }).click();
  await page.locator('.handbook-record').click();
  await expect(page.getByLabel('变动', { exact: true })).toHaveValue('验收编辑后保存');
  await button('取消').click();
  await directory.getByRole('button', { name: /主题团日活动/ }).click();
  const image = await page.locator('.brand-mark').screenshot();
  await button('新增记录').click();
  await page.getByLabel('团日活动名称', { exact: true }).fill('消防安全学习（测试记录）');
  await page.getByLabel('活动时间', { exact: true }).fill(campusClock().date);
  await page.getByLabel('活动地点', { exact: true }).fill('教室');
  await page.getByLabel('组织者', { exact: true }).fill('测试支部');
  await page.getByLabel('参与人数', { exact: true }).fill('30');
  await page.getByLabel('活动情况', { exact: true }).fill('测试用活动记录，用于验证手册填写、图片留存和备份恢复。');
  await page.getByLabel('活动总结', { exact: true }).fill('测试用总结，不代表真实开展活动。');
  await page.getByLabel('添加图片资料').setInputFiles({ name: '测试图片.png', mimeType: 'image/png', buffer: image });
  await expect(page.getByRole('img', { name: '测试图片.png' })).toBeVisible();
  await button('保存记录').click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.handbook-record')).toContainText('1 张图片');
  await expect(page.locator('.handbook-reminders').getByText('已登记 1 次')).toBeVisible();
  await expect(page.locator('.handbook-record')).toContainText('消防安全学习');
  await expect(page).toHaveURL(/#handbook$/);
  const noOverflow = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await noOverflow();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath('handbook-desktop.png'), fullPage: true });
  await page.locator('.handbook-record').click();
  await expect(page.getByRole('img', { name: '测试图片.png' })).toBeVisible();
  await page.screenshot({ path: info.outputPath('handbook-form.png') });
  await button('取消').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(directory.getByRole('button', { name: /团员名册/ })).toBeHidden();
  await page.getByLabel('选择手册台账').selectOption('members');
  await expect(page.locator('.handbook-record')).toContainText('验收同学');
  await page.getByLabel('选择手册台账').selectOption('activity');
  await noOverflow();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath('handbook-mobile.png'), fullPage: true });
  await page.locator('.handbook-record').click();
  await expect(page.getByLabel('团日活动名称')).toHaveValue('消防安全学习（测试记录）');
  await noOverflow();
  await button('取消').click();
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.locator('nav a[href="#backup"]').click();
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: /导出备份/ }).click();
  const downloaded = await downloading;
  const file = info.outputPath('handbook-backup.json');
  await downloaded.saveAs(file);
  const backup = JSON.parse(readFileSync(file, 'utf8'));
  expect(backup.version).toBe(2);
  expect(backup.handbook).toHaveLength(2);
  expect(backup.handbook.find((r: { kind: string }) => r.kind === 'activity').photos[0].data).toMatch(/^data:image\/png;base64,/);
  await page.locator('nav a[href="#handbook"]').click();
  await directory.getByRole('button', { name: /主题团日活动/ }).click();
  await page.locator('.handbook-record').click();
  await button('删除记录').click();
  await button('取消删除').click();
  await expect(page.getByLabel('团日活动名称')).toBeVisible();
  await button('删除记录').click();
  await button('确认删除记录').click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByText('尚未登记')).toBeVisible();
  await page.locator('nav a[href="#backup"]').click();
  await page.getByLabel('备份文件').setInputFiles(file);
  await expect(page.getByText('恢复前核对')).toBeVisible();
  await page.getByRole('checkbox').check();
  await button('确认覆盖并恢复').click();
  await expect(page.getByText('恢复前核对')).toHaveCount(0);
  await page.locator('nav a[href="#handbook"]').click();
  await directory.getByRole('button', { name: /主题团日活动/ }).click();
  await page.locator('.handbook-record').click();
  await expect(page.getByRole('img', { name: '测试图片.png' })).toBeVisible();
  await button('取消').click();
  // 同一测试服务供其他原有流程使用，清理本用例创建的手册记录。
  for (const record of backup.handbook) {
    const response = await page.request.delete('/api/handbook/' + record.id, { headers: { 'x-classflow-request': '1', origin: new URL(page.url()).origin } });
    expect(response.status()).toBe(204);
  }
  expect(errors).toEqual([]);
});
